Step 1: Extract Transaction KPIs
--------------------------------------------
CREATE OR REPLACE TEMP TABLE TXN_KPI AS
SELECT
    TXN_DATE                  AS REPORT_DATE,
    SUM(TOTAL_TXNS)           AS TOTAL_TRANSACTIONS,
    SUM(TOTAL_TXN_AMOUNT)     AS TOTAL_TRANSACTION_AMOUNT,
    SUM(SUSPICIOUS_TXNS)      AS TOTAL_SUSPICIOUS_TXNS,
    SUM(SUSPICIOUS_AMOUNT)    AS FRAUD_AMOUNT
FROM GLD_TXN_SUMMARY
GROUP BY TXN_DATE;


Step 2: Extract Alert KPIs
---------------------------------
CREATE OR REPLACE TEMP TABLE ALERT_KPI AS
SELECT
    DATE(CREATED_TS) AS REPORT_DATE,
    COUNT(*) AS TOTAL_ALERTS,
    SUM(CASE WHEN ALERT_STAT*S='OPEN' THEN 1 ELSE 0  END ) AS OPEN_ALERTS,
    SUM(CASE WHEN ALERT_STATUS='CLOSED' THEN 1 ELSE 0  END )AS CLOSED_ALERTS,
    SUM(CASE WHEN SEVERITY='HiGH' THEN 1 ELSE 0  END) AS HIGH_RISK_ALERTS,
    SUM(CASE WHEN SEVERITY='CRITICAL' THEN 1 ELSE 0  END)  AS CRITICAL_ALERTS
FROM GLD_FRAUD_A*ERT
GROUP BY DATE(CREATED_TS);

Step 3: Extract Customer Risk KPIs
--------------------------------------------------
CREATE OR REPLACE TEMP *ABLE CUSTOMER_KPI AS
SELECT
   CURRENT_DATE() AS REPORT_DATE,
   COUNT(*) AS TOTAL_CUSTOMERS,
   SUM(CASE WHEN RISK_BAND IN ('HIGH','CRITICAL')  THEN 1 ELSE 0  END) AS HIGH_RISK_CUSTOMERS
FROM GLD_CUSTOMER_RISK;

Step 4: Extract Investigation KPIs
---------------------------------------------
CREATE OR REPLACE TEMP TABLE CASE_KPI AS
SELECT
CURRENT_DATE() AS REPORT_DATE,
    SUM(CASE WHEN CASE_STATUS IN ('*PEN','IN_PROGRESS') THEN 1 ELSE 0 END) AS OPEN_CASES,
    SUM(CASE WHEN CASE_STATUS LIKE  'CLOSED%'  THEN 1 ELSE 0  END) AS CLOSED_CASES
FROM GLD_INVESTIGATION_QUEUE;

