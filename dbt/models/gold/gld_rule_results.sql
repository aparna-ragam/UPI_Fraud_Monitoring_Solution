    RULE_NAME,
    TRANSACTION_ID,
    CUSTOMER_ID,
    ACCOUNT_ID,
    RISK_SCORE,
    SEVERITY,
    RULE_STATUS,
    DETECTED_TS,
    LOAD_TS
)

SELECT
    UUID_STRING(),
    RULE_ID,
    RULE_NAME,
    TRANSACTION_ID,
    CUSTOMER_ID,
    ACCOUNT_ID,
    RISK_SCORE,
    CASE
        WHEN RISK_SCORE >= 95 THEN 'CRITICAL'
        WHEN RISK_SCORE >= 85 THEN 'HIGH'
